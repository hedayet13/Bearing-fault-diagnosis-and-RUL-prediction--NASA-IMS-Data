%% ============================================================
%% LOCAL FUNCTION 1:
%% BEARING-WISE GPR-BASED RUL ESTIMATION
%% ============================================================

function result = ...
    bearingWiseGPRRUL( ...
    AA, ...
    chList, ...
    baselineRatio, ...
    lateRatio, ...
    smoothWindow, ...
    thresholdK, ...
    samplingInterval_minutes, ...
    futureHorizon, ...
    trainRatioGPR)


    %% ========================================================
    %% FIND COMMON SAMPLE COUNT AND FEATURE DIMENSION
    %% ========================================================

    minSamples = ...
        inf;


    minFeatureDim = ...
        inf;


    for k = 1:numel(chList)


        ch = ...
            chList(k);


        minSamples = ...
            min( ...
            minSamples, ...
            size(AA{ch},1));


        minFeatureDim = ...
            min( ...
            minFeatureDim, ...
            size(AA{ch},2));


    end


    %% ========================================================
    %% FUSE CHANNELS BELONGING TO SAME BEARING
    %%
    %% For IMS Dataset 2, each bearing has one channel.
    %% Therefore this simply uses the corresponding channel.
    %% ========================================================

    X_bearing = ...
        [];


    for k = 1:numel(chList)


        ch = ...
            chList(k);


        Xch = ...
            double( ...
            AA{ch});


        Xch( ...
            ~isfinite(Xch)) = ...
            0;


        Xch = ...
            Xch( ...
            1:minSamples, ...
            1:minFeatureDim);


        X_bearing = ...
            [ ...
            X_bearing, ...
            Xch ...
            ];


    end


    X = ...
        X_bearing;


    X( ...
        ~isfinite(X)) = ...
        0;


    [numSamples,numFeatures] = ...
        size(X);


    %% ========================================================
    %% BASELINE
    %% ========================================================

    numBaseline = ...
        max( ...
        5, ...
        round( ...
        baselineRatio * ...
        numSamples));


    X_base = ...
        X( ...
        1:numBaseline, ...
        :);


    mu_base = ...
        mean( ...
        X_base, ...
        1);


    sigma_base = ...
        std( ...
        X_base, ...
        0, ...
        1);


    sigma_base( ...
        sigma_base == 0) = ...
        eps;


    %% ========================================================
    %% RSE HEALTH INDICATOR
    %% ========================================================

    RSE = ...
        zeros( ...
        numSamples, ...
        1);


    for i = 1:numSamples


        relative_error = ...
            ( ...
            X(i,:) - ...
            mu_base ...
            ) ./ ...
            sigma_base;


        RSE(i) = ...
            sqrt( ...
            mean( ...
            relative_error.^2));


    end


    %% ========================================================
    %% SMOOTH HI
    %% ========================================================

    localSmoothWindow = ...
        smoothWindow;


    if localSmoothWindow >= numSamples


        localSmoothWindow = ...
            max( ...
            3, ...
            round( ...
            numSamples / 20));


    end


    HI = ...
        smoothdata( ...
        RSE, ...
        'movmean', ...
        localSmoothWindow);


    %% ========================================================
    %% NORMALIZE HI
    %%
    %% Same retrospective normalization as your original code.
    %% ========================================================

    HI_min = ...
        min(HI);


    HI_max = ...
        max(HI);


    HI_norm = ...
        ( ...
        HI - ...
        HI_min ...
        ) ./ ...
        ( ...
        HI_max - ...
        HI_min + ...
        eps);


    %% ========================================================
    %% ADAPTIVE THRESHOLD
    %% ========================================================

    baseline_HI = ...
        HI_norm( ...
        1:numBaseline);


    numLate = ...
        max( ...
        10, ...
        round( ...
        lateRatio * ...
        numSamples));


    numLate = ...
        min( ...
        numLate, ...
        numSamples);


    late_HI = ...
        HI_norm( ...
        end-numLate+1:end);


    threshold_baseline = ...
        mean( ...
        baseline_HI) + ...
        thresholdK * ...
        std( ...
        baseline_HI);


    threshold_late = ...
        mean( ...
        late_HI) - ...
        0.5 * ...
        std( ...
        late_HI);


    threshold_percentile = ...
        prctile( ...
        HI_norm, ...
        90);


    failureThreshold = ...
        max( ...
        [ ...
        threshold_baseline, ...
        threshold_late, ...
        threshold_percentile ...
        ]);


    failureThreshold = ...
        min( ...
        failureThreshold, ...
        0.98);


    failureThreshold = ...
        max( ...
        failureThreshold, ...
        threshold_baseline);


    %% ========================================================
    %% TIME INDEX
    %% ========================================================

    timeIndex = ...
        (1:numSamples)';


    %% ========================================================
    %% GPR TRAINING
    %% ========================================================

    numTrainGPR = ...
        round( ...
        trainRatioGPR * ...
        numSamples);


    numTrainGPR = ...
        max( ...
        2, ...
        min( ...
        numTrainGPR, ...
        numSamples-1));


    X_train_time = ...
        timeIndex( ...
        1:numTrainGPR);


    Y_train_HI = ...
        HI_norm( ...
        1:numTrainGPR);


    fprintf( ...
        'GPR training samples = %d / %d\n', ...
        numTrainGPR, ...
        numSamples);


    %% ========================================================
    %% GPR MODEL
    %%
    %% Same downstream GPR model for both methods.
    %% ========================================================

    gprMdl = ...
        fitrgp( ...
        ...
        X_train_time, ...
        Y_train_HI, ...
        ...
        'KernelFunction', ...
        'squaredexponential', ...
        ...
        'BasisFunction', ...
        'linear', ...
        ...
        'Standardize', ...
        true, ...
        ...
        'OptimizeHyperparameters', ...
        { ...
        'KernelScale', ...
        'Sigma' ...
        }, ...
        ...
        'HyperparameterOptimizationOptions', ...
        struct( ...
        ...
        'AcquisitionFunctionName', ...
        'expected-improvement-plus', ...
        ...
        'MaxObjectiveEvaluations', ...
        30, ...
        ...
        'ShowPlots', ...
        false, ...
        ...
        'Verbose', ...
        0));


    %% ========================================================
    %% PREDICTION
    %% ========================================================

    futureTime = ...
        ( ...
        1: ...
        (numSamples + futureHorizon) ...
        )';


    [ ...
        HI_pred, ...
        HI_sd, ...
        HI_ci ...
        ] = ...
        predict( ...
        gprMdl, ...
        futureTime);


    HI_pred( ...
        HI_pred < 0) = ...
        0;


    HI_pred( ...
        HI_pred > 1.2) = ...
        1.2;


    %% ========================================================
    %% CURRENT PROGNOSTIC POINT
    %%
    %% End of 70% GPR observation region.
    %% ========================================================

    currentPoint = ...
        numTrainGPR;


    %% ========================================================
    %% SEARCH FOR FAILURE AFTER CURRENT POINT ONLY
    %% ========================================================

    futureFailureIdx = ...
        find( ...
        HI_pred( ...
        currentPoint+1:end) ...
        >= ...
        failureThreshold, ...
        ...
        1, ...
        'first');


    if isempty( ...
            futureFailureIdx)


        predictedFailurePoint = ...
            numSamples + ...
            futureHorizon;


    else


        predictedFailurePoint = ...
            currentPoint + ...
            futureFailureIdx;


    end


    %% ========================================================
    %% RUL
    %% ========================================================

    RUL_pred_samples = ...
        max( ...
        predictedFailurePoint - ...
        currentPoint, ...
        0);


    RUL_pred_hours = ...
        RUL_pred_samples * ...
        samplingInterval_minutes / ...
        60;


    RUL_pred_days = ...
        RUL_pred_hours / ...
        24;


    %% ========================================================
    %% STORE RESULTS
    %% ========================================================

    result.X_bearing = ...
        X;


    result.RSE = ...
        RSE;


    result.HI = ...
        HI;


    result.HI_norm = ...
        HI_norm;


    result.HI_min = ...
        HI_min;


    result.HI_max = ...
        HI_max;


    result.failureThreshold = ...
        failureThreshold;


    result.threshold_baseline = ...
        threshold_baseline;


    result.threshold_late = ...
        threshold_late;


    result.threshold_percentile = ...
        threshold_percentile;


    result.gprMdl = ...
        gprMdl;


    result.timeIndex = ...
        timeIndex;


    result.futureTime = ...
        futureTime;


    result.HI_pred = ...
        HI_pred;


    result.HI_sd = ...
        HI_sd;


    result.HI_ci = ...
        HI_ci;


    result.currentPoint = ...
        currentPoint;


    result.predictedFailurePoint = ...
        predictedFailurePoint;


    result.RUL_pred_samples = ...
        RUL_pred_samples;


    result.RUL_pred_hours = ...
        RUL_pred_hours;


    result.RUL_pred_days = ...
        RUL_pred_days;


    result.numSamples = ...
        numSamples;


    result.numFeatures = ...
        numFeatures;


    result.numTrainGPR = ...
        numTrainGPR;


    result.numBaseline = ...
        numBaseline;


    result.numLate = ...
        numLate;


    result.smoothWindow = ...
        localSmoothWindow;


end
