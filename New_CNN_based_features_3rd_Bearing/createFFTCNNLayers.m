%% ============================================================
%% Local Function 3: Create FFT-CNN Layers
%% ============================================================

function layers = createFFTCNNLayers(numFFTPoints, featureDim, numFilters1, numFilters2, numFilters3)

layers = [
    imageInputLayer([numFFTPoints 1 1], ...
    'Normalization','none', ...
    'Name','input')

    convolution2dLayer([9 1], numFilters1, ...
    'Padding','same', ...
    'Name','conv1')
    batchNormalizationLayer('Name','bn1')
    reluLayer('Name','relu1')
    maxPooling2dLayer([2 1], ...
    'Stride',[2 1], ...
    'Name','pool1')

    convolution2dLayer([7 1], numFilters2, ...
    'Padding','same', ...
    'Name','conv2')
    batchNormalizationLayer('Name','bn2')
    reluLayer('Name','relu2')
    maxPooling2dLayer([2 1], ...
    'Stride',[2 1], ...
    'Name','pool2')

    convolution2dLayer([5 1], numFilters3, ...
    'Padding','same', ...
    'Name','conv3')
    batchNormalizationLayer('Name','bn3')
    reluLayer('Name','relu3')
    maxPooling2dLayer([2 1], ...
    'Stride',[2 1], ...
    'Name','pool3')

    fullyConnectedLayer(featureDim, ...
    'Name','cnn_features')
    reluLayer('Name','feature_relu')

    fullyConnectedLayer(2, ...
    'Name','fc_output')
    softmaxLayer('Name','softmax')
    classificationLayer('Name','classification')
    ];

end