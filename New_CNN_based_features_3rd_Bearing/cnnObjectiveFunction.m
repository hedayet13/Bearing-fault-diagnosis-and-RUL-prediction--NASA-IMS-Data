
%% ============================================================
%% Local Function 4: Bayesian Optimization Objective Function
%% ============================================================

function objective = cnnObjectiveFunction(optVars, XTrain, YTrain, numFFTPoints)

layers = createFFTCNNLayers( ...
    numFFTPoints, ...
    optVars.FeatureDim, ...
    optVars.NumFilters1, ...
    optVars.NumFilters2, ...
    optVars.NumFilters3);

options = trainingOptions('adam', ...
    'MaxEpochs',10, ...
    'MiniBatchSize',optVars.MiniBatchSize, ...
    'InitialLearnRate',optVars.InitialLearnRate, ...
    'L2Regularization',optVars.L2Regularization, ...
    'Shuffle','every-epoch', ...
    'Verbose',false, ...
    'Plots','none', ...
    'ValidationFrequency',30);

try
    net = trainNetwork(XTrain, YTrain, layers, options);

    YPred = classify(net, XTrain);

    accuracy = mean(YPred == YTrain);

    objective = 1 - accuracy;

catch ME
    warning('Training failed: %s', ME.message);
    objective = 1;
end

end