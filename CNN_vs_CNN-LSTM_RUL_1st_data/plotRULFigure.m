%% ============================================================
%% LOCAL FUNCTION 2:
%% PLOT RUL FIGURE
%% ============================================================

function plotRULFigure( ...
    result, ...
    plotTitle)


    timeIndex = ...
        result.timeIndex;


    futureTime = ...
        result.futureTime;


    HI_norm = ...
        result.HI_norm;


    HI_pred = ...
        result.HI_pred;


    HI_ci = ...
        result.HI_ci;


    failureThreshold = ...
        result.failureThreshold;


    numTrainGPR = ...
        result.numTrainGPR;


    predictedFailurePoint = ...
        result.predictedFailurePoint;


    currentPoint = ...
        result.currentPoint;


    %% ========================================================
    %% BEGIN PLOT
    %% ========================================================

    hold on;


    %% ========================================================
    %% OBSERVED HEALTH INDICATOR
    %% ========================================================

    plot( ...
        timeIndex, ...
        HI_norm, ...
        ...
        'Color', ...
        [0 0 0], ...
        ...
        'LineStyle', ...
        '-', ...
        ...
        'LineWidth', ...
        2.0, ...
        ...
        'Marker', ...
        'o', ...
        ...
        'MarkerIndices', ...
        1:150:length(timeIndex), ...
        ...
        'MarkerSize', ...
        4);


    %% ========================================================
    %% GPR PREDICTION
    %% ========================================================

    plot( ...
        futureTime, ...
        HI_pred, ...
        ...
        'Color', ...
        [0 0.4470 0.7410], ...
        ...
        'LineStyle', ...
        '--', ...
        ...
        'LineWidth', ...
        2.2);


    %% ========================================================
    %% 95% CONFIDENCE INTERVAL: LOWER
    %% ========================================================

    plot( ...
        futureTime, ...
        HI_ci(:,1), ...
        ...
        'Color', ...
        [0.8500 0.3250 0.0980], ...
        ...
        'LineStyle', ...
        ':', ...
        ...
        'LineWidth', ...
        1.8);


    %% ========================================================
    %% 95% CONFIDENCE INTERVAL: UPPER
    %% ========================================================

    plot( ...
        futureTime, ...
        HI_ci(:,2), ...
        ...
        'Color', ...
        [0.8500 0.3250 0.0980], ...
        ...
        'LineStyle', ...
        ':', ...
        ...
        'LineWidth', ...
        1.8);


    %% ========================================================
    %% FAILURE THRESHOLD
    %% ========================================================

    yline( ...
        failureThreshold, ...
        ...
        'Color', ...
        [0.4940 0.1840 0.5560], ...
        ...
        'LineStyle', ...
        '-.', ...
        ...
        'LineWidth', ...
        2.2);


    %% ========================================================
    %% END OF GPR TRAINING / CURRENT PROGNOSTIC POINT
    %% ========================================================

    xline( ...
        numTrainGPR, ...
        ...
        'Color', ...
        [0.4660 0.6740 0.1880], ...
        ...
        'LineStyle', ...
        '--', ...
        ...
        'LineWidth', ...
        1.8);


    %% ========================================================
    %% PREDICTED FAILURE POINT
    %% ========================================================

    xline( ...
        predictedFailurePoint, ...
        ...
        'Color', ...
        [0.6350 0.0780 0.1840], ...
        ...
        'LineStyle', ...
        ':', ...
        ...
        'LineWidth', ...
        2.2);


    %% ========================================================
    %% LABELS
    %% ========================================================

    xlabel( ...
        'Run Index', ...
        ...
        'FontSize', ...
        12, ...
        ...
        'FontWeight', ...
        'bold');


    ylabel( ...
        'Normalized HI', ...
        ...
        'FontSize', ...
        12, ...
        ...
        'FontWeight', ...
        'bold');


    title( ...
        plotTitle, ...
        ...
        'FontSize', ...
        13, ...
        ...
        'FontWeight', ...
        'bold');


    %% ========================================================
    %% LEGEND
    %% ========================================================

    legend( ...
        ...
        'Observed HI', ...
        'GPR Prediction', ...
        '95% CI', ...
        '', ...
        'Failure Th.', ...
        'Prediction Point', ...
        'Failure Point', ...
        ...
        'Location', ...
        'best', ...
        ...
        'FontSize', ...
        8);


    %% ========================================================
    %% GRID / AXIS FORMAT
    %% ========================================================

    grid on;


    box on;


    set( ...
        gca, ...
        ...
        'FontSize', ...
        11, ...
        ...
        'LineWidth', ...
        1.2, ...
        ...
        'TickDir', ...
        'out');


    ylim( ...
        [-0.2 1.05]);


    %% ========================================================
    %% OPTIONAL RUL TEXT
    %% ========================================================

    RULtext = ...
        sprintf( ...
        ['Prediction point = %d\n', ...
         'Failure point = %d\n', ...
         'RUL = %.2f h'], ...
        ...
        currentPoint, ...
        predictedFailurePoint, ...
        result.RUL_pred_hours);


    text( ...
        0.02, ...
        0.97, ...
        RULtext, ...
        ...
        'Units', ...
        'normalized', ...
        ...
        'VerticalAlignment', ...
        'top', ...
        ...
        'FontSize', ...
        9, ...
        ...
        'FontWeight', ...
        'bold', ...
        ...
        'BackgroundColor', ...
        'w', ...
        ...
        'EdgeColor', ...
        [0.5 0.5 0.5]);


    hold off;


end