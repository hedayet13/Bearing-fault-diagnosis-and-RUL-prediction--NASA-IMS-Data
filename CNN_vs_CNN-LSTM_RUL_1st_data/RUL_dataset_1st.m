clear;
close all;

%% ============================================================
%% Bearing-Wise RUL Comparison:
%%
%% Proposed Method:
%% BayesOpt FFT-1D-CNN Features + GPR
%%
%% Benchmark Method:
%% FFT-CNN-LSTM Features + GPR
%% CNN-LSTM without Bayesian Optimization
%%
%% IMS Dataset 1
%%
%% Bearing 1 -> Ch 1-2
%% Bearing 2 -> Ch 3-4
%% Bearing 3 -> Ch 5-6
%% Bearing 4 -> Ch 7-8
%%
%% IMPORTANT:
%% The same downstream HI + GPR + RUL framework is applied
%% to both proposed and benchmark feature representations.
%% ============================================================


%% ============================================================
%% LOAD PROPOSED FFT-1D-CNN FEATURES
%% ============================================================

load( ...
    'X_FFT_1DCNN_features_IMS_1st_test_BayesOpt_NoNorm.mat');


if ~exist('X_cnn_all_channels','var')

    error( ...
        ['Variable "X_cnn_all_channels" was not found in ', ...
         'the proposed FFT-1D-CNN feature file.']);

end


AA_CNN = ...
    X_cnn_all_channels;


clear X_cnn_all_channels;


%% ============================================================
%% LOAD BENCHMARK FFT-CNN-LSTM FEATURES
%% ============================================================

load( ...
    'X_FFT_CNN_LSTM_features_IMS_1st_test_NoBayesOpt.mat');


if ~exist('X_cnn_lstm_all_channels','var')

    error( ...
        ['Variable "X_cnn_lstm_all_channels" was not found ', ...
         'in the benchmark FFT-CNN-LSTM feature file.']);

end


AA_CNN_LSTM = ...
    X_cnn_lstm_all_channels;


clear X_cnn_lstm_all_channels;


%% ============================================================
%% VERIFY CHANNEL COUNTS
%% ============================================================

numChannelsCNN = ...
    numel(AA_CNN);


numChannelsCNNLSTM = ...
    numel(AA_CNN_LSTM);


fprintf('\n============================================\n');
fprintf('IMS DATASET 1 RUL FEATURE INFORMATION\n');
fprintf('============================================\n');


fprintf( ...
    'Proposed FFT-1D-CNN channels  = %d\n', ...
    numChannelsCNN);


fprintf( ...
    'Benchmark FFT-CNN-LSTM channels = %d\n', ...
    numChannelsCNNLSTM);


if numChannelsCNN ~= 8

    error( ...
        ['IMS Dataset 1 proposed feature file should contain ', ...
         '8 channels. Found %d.'], ...
         numChannelsCNN);

end


if numChannelsCNNLSTM ~= 8

    error( ...
        ['IMS Dataset 1 benchmark feature file should contain ', ...
         '8 channels. Found %d.'], ...
         numChannelsCNNLSTM);

end


%% ============================================================
%% BEARING-WISE CHANNEL MAPPING
%% ============================================================

bearingNames = { ...
    'Bearing 1', ...
    'Bearing 2', ...
    'Bearing 3', ...
    'Bearing 4' ...
    };


bearingChannels = { ...
    [1 2]; ...
    [3 4]; ...
    [5 6]; ...
    [7 8] ...
    };


numBearings = ...
    numel( ...
    bearingChannels);


%% ============================================================
%% RUL SETTINGS
%% ============================================================

baselineRatio = ...
    0.10;


lateRatio = ...
    0.15;


smoothWindow = ...
    51;


thresholdK = ...
    3;


samplingInterval_minutes = ...
    10;


futureHorizon = ...
    600;


trainRatioGPR = ...
    0.70;


fprintf('\n============================================\n');
fprintf('RUL SETTINGS\n');
fprintf('============================================\n');


fprintf( ...
    'Baseline ratio          = %.2f\n', ...
    baselineRatio);


fprintf( ...
    'Late-life ratio         = %.2f\n', ...
    lateRatio);


fprintf( ...
    'Smoothing window        = %d\n', ...
    smoothWindow);


fprintf( ...
    'Threshold K             = %.2f\n', ...
    thresholdK);


fprintf( ...
    'Sampling interval       = %.2f min\n', ...
    samplingInterval_minutes);


fprintf( ...
    'Future horizon          = %d runs\n', ...
    futureHorizon);


fprintf( ...
    'GPR training ratio      = %.2f\n', ...
    trainRatioGPR);


%% ============================================================
%% RESULT CONTAINERS
%% ============================================================

RUL_CNN = ...
    cell( ...
    numBearings, ...
    1);


RUL_CNN_LSTM = ...
    cell( ...
    numBearings, ...
    1);


%% ============================================================
%% RUN BEARING-WISE RUL FOR BOTH METHODS
%% ============================================================

for b = 1:numBearings


    fprintf('\n====================================================\n');


    fprintf( ...
        'Processing %s\n', ...
        bearingNames{b});


    fprintf('====================================================\n');


    chList = ...
        bearingChannels{b};


    fprintf( ...
        'Channels: %s\n', ...
        mat2str(chList));


    %% ========================================================
    %% PROPOSED METHOD:
    %% FFT-1D-CNN + GPR
    %% ========================================================

    fprintf('\nRunning proposed FFT-1D-CNN + GPR...\n');


    RUL_CNN{b} = ...
        bearingWiseGPRRUL( ...
        AA_CNN, ...
        chList, ...
        baselineRatio, ...
        lateRatio, ...
        smoothWindow, ...
        thresholdK, ...
        samplingInterval_minutes, ...
        futureHorizon, ...
        trainRatioGPR);


    %% ========================================================
    %% BENCHMARK METHOD:
    %% FFT-CNN-LSTM + GPR
    %% ========================================================

    fprintf('\nRunning benchmark FFT-CNN-LSTM + GPR...\n');


    RUL_CNN_LSTM{b} = ...
        bearingWiseGPRRUL( ...
        AA_CNN_LSTM, ...
        chList, ...
        baselineRatio, ...
        lateRatio, ...
        smoothWindow, ...
        thresholdK, ...
        samplingInterval_minutes, ...
        futureHorizon, ...
        trainRatioGPR);


    %% ========================================================
    %% DISPLAY RESULTS
    %% ========================================================

    fprintf('\n--------------------------------------------\n');


    fprintf( ...
        '%s Proposed FFT-1D-CNN:\n', ...
        bearingNames{b});


    fprintf( ...
        'Current point           = %d\n', ...
        RUL_CNN{b}.currentPoint);


    fprintf( ...
        'Predicted failure point = %d\n', ...
        RUL_CNN{b}.predictedFailurePoint);


    fprintf( ...
        'Predicted RUL           = %.2f hours\n', ...
        RUL_CNN{b}.RUL_pred_hours);


    fprintf( ...
        'Predicted RUL           = %.4f days\n', ...
        RUL_CNN{b}.RUL_pred_days);


    fprintf( ...
        'Failure threshold       = %.4f\n', ...
        RUL_CNN{b}.failureThreshold);


    fprintf('\n');


    fprintf( ...
        '%s Benchmark FFT-CNN-LSTM:\n', ...
        bearingNames{b});


    fprintf( ...
        'Current point           = %d\n', ...
        RUL_CNN_LSTM{b}.currentPoint);


    fprintf( ...
        'Predicted failure point = %d\n', ...
        RUL_CNN_LSTM{b}.predictedFailurePoint);


    fprintf( ...
        'Predicted RUL           = %.2f hours\n', ...
        RUL_CNN_LSTM{b}.RUL_pred_hours);


    fprintf( ...
        'Predicted RUL           = %.4f days\n', ...
        RUL_CNN_LSTM{b}.RUL_pred_days);


    fprintf( ...
        'Failure threshold       = %.4f\n', ...
        RUL_CNN_LSTM{b}.failureThreshold);


    %% ========================================================
    %% SIDE-BY-SIDE RUL FIGURE
    %% ========================================================

    figure;


    clf;


    set( ...
        gcf, ...
        'Color', ...
        'w', ...
        ...
        'Position', ...
        [100 100 1600 650]);


    tiledlayout( ...
        1, ...
        2, ...
        ...
        'TileSpacing', ...
        'compact', ...
        ...
        'Padding', ...
        'compact');


    %% --------------------------------------------------------
    %% LEFT:
    %% Proposed FFT-1D-CNN
    %% --------------------------------------------------------

    nexttile;


    plotRULFigure( ...
        RUL_CNN{b}, ...
        sprintf( ...
        '%s: Proposed FFT-1D-CNN + GPR', ...
        bearingNames{b}));


    %% --------------------------------------------------------
    %% RIGHT:
    %% Benchmark FFT-CNN-LSTM
    %% --------------------------------------------------------

    nexttile;


    plotRULFigure( ...
        RUL_CNN_LSTM{b}, ...
        sprintf( ...
        '%s: Benchmark FFT-CNN-LSTM + GPR', ...
        bearingNames{b}));


    %% ========================================================
    %% OVERALL TITLE
    %% ========================================================

    sgtitle( ...
        sprintf( ...
        '%s Bearing-Wise RUL Comparison', ...
        bearingNames{b}), ...
        ...
        'FontSize', ...
        18, ...
        ...
        'FontWeight', ...
        'bold');


    %% ========================================================
    %% SAVE FIGURES
    %% ========================================================

    exportgraphics( ...
        gcf, ...
        sprintf( ...
        ['Bearing_%d_RUL_Comparison_', ...
         'Proposed_CNN_vs_Benchmark_CNN_LSTM.jpg'], ...
         b), ...
        ...
        'Resolution', ...
        600);


    savefig( ...
        gcf, ...
        sprintf( ...
        ['Bearing_%d_RUL_Comparison_', ...
         'Proposed_CNN_vs_Benchmark_CNN_LSTM.fig'], ...
         b));


end


