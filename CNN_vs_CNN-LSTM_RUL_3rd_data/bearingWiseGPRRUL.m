%% ============================================================
%% LOCAL FUNCTION 1
%%
%% BEARING-WISE GPR-BASED RUL ESTIMATION
%% ============================================================

function result = bearingWiseGPRRUL( ...
    AA, ...
    chList, ...
    baselineRatio, ...
    lateRatio, ...
    smoothWindow, ...
    thresholdK, ...
    samplingInterval_minutes, ...
    futureHorizon, ...
    trainRatioGPR)


%% ============================================================
%% FIND COMMON SAMPLE COUNT AND FEATURE DIMENSION
%% ============================================================

minSamples = ...
    inf;


minFeatureDim = ...
    inf;


for k = 1:numel(chList)


    ch = ...
        chList(k);


    minSamples = ...
        min( ...
        minSamples, ...
        size(AA{ch},1));


    minFeatureDim = ...
        min( ...
        minFeatureDim, ...
        size(AA{ch},2));


end


%% ============================================================
%% PREPARE / FUSE BEARING FEATURES
%% ============================================================

X_bearing = ...
    [];


for k = 1:numel(chList)


    ch = ...
        chList(k);


    Xch = ...
        double(AA{ch});


    %% --------------------------------------------------------
    %% Replace NaN / Inf
    %% --------------------------------------------------------

    Xch(~isfinite(Xch)) = ...
        0;


    %% --------------------------------------------------------
    %% Common samples/features
    %% --------------------------------------------------------

    Xch = ...
        Xch( ...
        1:minSamples, ...
        1:minFeatureDim);


    %% --------------------------------------------------------
    %% Horizontal feature fusion
    %% --------------------------------------------------------

    X_bearing = ...
        [X_bearing, Xch];


end


X = ...
    X_bearing;


X(~isfinite(X)) = ...
    0;


[numSamples,numFeatures] = ...
    size(X);


%% ============================================================
%% VERIFY SUFFICIENT DATA
%% ============================================================

if numSamples < 20

    error( ...
        ['Insufficient samples for RUL analysis. ', ...
         'Only %d samples were found.'], ...
         numSamples);

end


%% ============================================================
%% HEALTHY BASELINE
%% ============================================================

numBaseline = ...
    max( ...
    5, ...
    round( ...
    baselineRatio * ...
    numSamples));


numBaseline = ...
    min( ...
    numBaseline, ...
    numSamples);


X_base = ...
    X( ...
    1:numBaseline, ...
    :);


mu_base = ...
    mean( ...
    X_base, ...
    1);


sigma_base = ...
    std( ...
    X_base, ...
    0, ...
    1);


%% ============================================================
%% PROTECT ZERO / INVALID BASELINE STD
%% ============================================================

sigma_base( ...
    sigma_base == 0) = ...
    eps;


sigma_base( ...
    ~isfinite(sigma_base)) = ...
    eps;


%% ============================================================
%% RSE HEALTH INDICATOR
%%
%% RSE_i =
%%
%% sqrt(
%% mean(
%% ((X_i - mu_base)./sigma_base).^2
%% )
%% )
%% ============================================================

RSE = ...
    zeros( ...
    numSamples, ...
    1);


for i = 1:numSamples


    relative_error = ...
        ( ...
        X(i,:) - ...
        mu_base ...
        ) ./ ...
        sigma_base;


    relative_error( ...
        ~isfinite(relative_error)) = ...
        0;


    RSE(i) = ...
        sqrt( ...
        mean( ...
        relative_error.^2));


end


%% ============================================================
%% CHECK RSE
%% ============================================================

if any(~isfinite(RSE))

    error( ...
        'RSE contains NaN or Inf after calculation.');

end


%% ============================================================
%% SMOOTH HEALTH INDICATOR
%% ============================================================

localSmoothWindow = ...
    smoothWindow;


if localSmoothWindow >= numSamples

    localSmoothWindow = ...
        max( ...
        3, ...
        round(numSamples/20));

end


HI = ...
    smoothdata( ...
    RSE, ...
    'movmean', ...
    localSmoothWindow);


HI(~isfinite(HI)) = ...
    0;


%% ============================================================
%% NORMALIZE HEALTH INDICATOR
%%
%% Same retrospective full-trajectory normalization
%% used in the previous IMS analyses.
%% ============================================================

HI_min = ...
    min(HI);


HI_max = ...
    max(HI);


HI_range = ...
    HI_max - ...
    HI_min;


if HI_range < 1e-12

    warning( ...
        ['Health indicator is nearly constant. ', ...
         'Using epsilon normalization protection.']);

end


HI_norm = ...
    ( ...
    HI - ...
    HI_min ...
    ) ./ ...
    ( ...
    HI_range + ...
    eps);


HI_norm(~isfinite(HI_norm)) = ...
    0;


%% ============================================================
%% ADAPTIVE FAILURE THRESHOLD
%% ============================================================

baseline_HI = ...
    HI_norm( ...
    1:numBaseline);


numLate = ...
    max( ...
    10, ...
    round( ...
    lateRatio * ...
    numSamples));


numLate = ...
    min( ...
    numLate, ...
    numSamples);


late_HI = ...
    HI_norm( ...
    end-numLate+1:end);


%% ------------------------------------------------------------
%% Baseline threshold
%% ------------------------------------------------------------

threshold_baseline = ...
    mean(baseline_HI) + ...
    thresholdK * ...
    std(baseline_HI);


%% ------------------------------------------------------------
%% Late-life threshold
%% ------------------------------------------------------------

threshold_late = ...
    mean(late_HI) - ...
    0.5 * ...
    std(late_HI);


%% ------------------------------------------------------------
%% Percentile threshold
%% ------------------------------------------------------------

threshold_percentile = ...
    prctile( ...
    HI_norm, ...
    90);


%% ------------------------------------------------------------
%% Final adaptive threshold
%% ------------------------------------------------------------

failureThreshold = ...
    max( ...
    [ ...
    threshold_baseline, ...
    threshold_late, ...
    threshold_percentile ...
    ]);


failureThreshold = ...
    min( ...
    failureThreshold, ...
    0.98);


failureThreshold = ...
    max( ...
    failureThreshold, ...
    threshold_baseline);


%% ============================================================
%% TIME INDEX
%% ============================================================

timeIndex = ...
    (1:numSamples)';


%% ============================================================
%% GPR TRAINING REGION
%% ============================================================

numTrainGPR = ...
    round( ...
    trainRatioGPR * ...
    numSamples);


numTrainGPR = ...
    max( ...
    2, ...
    min( ...
    numTrainGPR, ...
    numSamples-1));


X_train_time = ...
    double( ...
    timeIndex( ...
    1:numTrainGPR));


Y_train_HI = ...
    double( ...
    HI_norm( ...
    1:numTrainGPR));


%% ============================================================
%% NUMERICAL CHECKS
%% ============================================================

X_train_time(~isfinite(X_train_time)) = ...
    0;


Y_train_HI(~isfinite(Y_train_HI)) = ...
    0;


fprintf( ...
    'GPR training samples = %d / %d\n', ...
    numTrainGPR, ...
    numSamples);


%% ============================================================
%% CHECK HI VARIATION
%% ============================================================

Ystd = ...
    std(Y_train_HI);


Yrange = ...
    range(Y_train_HI);


fprintf( ...
    'Training HI range = %.8f\n', ...
    Yrange);


fprintf( ...
    'Training HI std   = %.8f\n', ...
    Ystd);


if ~isfinite(Ystd) || ...
        Ystd < 1e-6

    warning( ...
        ['HI within the GPR training region is nearly ', ...
         'constant. GPR extrapolation may be less reliable.']);

    Ystd = ...
        0.01;

end


%% ============================================================
%% ROBUST GPR SIGMA SETTINGS
%%
%% Key correction for the Cholesky error.
%% ============================================================

sigmaLowerBound = ...
    max( ...
    1e-4, ...
    0.01 * ...
    Ystd);


initialSigma = ...
    max( ...
    10 * ...
    sigmaLowerBound, ...
    0.05 * ...
    Ystd);


fprintf( ...
    'GPR SigmaLowerBound = %.8f\n', ...
    sigmaLowerBound);


fprintf( ...
    'Initial GPR Sigma   = %.8f\n', ...
    initialSigma);


%% ============================================================
%% PRIMARY GPR
%%
%% Bayesian optimization is retained because this is the
%% SAME common downstream prognosis model for both methods.
%%
%% The CNN-LSTM FEATURE LEARNER itself still uses NO BayesOpt.
%% ============================================================

GPRFitStatus = ...
    'BayesianOptimizedExactGPR';


try


    gprMdl = ...
        fitrgp( ...
        X_train_time, ...
        Y_train_HI, ...
        ...
        'KernelFunction', ...
        'squaredexponential', ...
        ...
        'BasisFunction', ...
        'linear', ...
        ...
        'Standardize', ...
        true, ...
        ...
        'Sigma', ...
        initialSigma, ...
        ...
        'SigmaLowerBound', ...
        sigmaLowerBound, ...
        ...
        'OptimizeHyperparameters', ...
        { ...
        'KernelScale', ...
        'Sigma' ...
        }, ...
        ...
        'HyperparameterOptimizationOptions', ...
        struct( ...
        'AcquisitionFunctionName', ...
        'expected-improvement-plus', ...
        'MaxObjectiveEvaluations', ...
        30, ...
        'ShowPlots', ...
        false, ...
        'Verbose', ...
        0));


catch ME1


    %% ========================================================
    %% FALLBACK 1
    %%
    %% Exact GPR with fixed robust Sigma.
    %% ========================================================

    fprintf('\n');

    warning( ...
        ['Bayesian-optimized GPR failed because of numerical ', ...
         'conditioning.\nAttempting stable exact GPR.\n', ...
         'Original error:\n%s'], ...
         ME1.message);


    GPRFitStatus = ...
        'StableExactGPR';


    try


        gprMdl = ...
            fitrgp( ...
            X_train_time, ...
            Y_train_HI, ...
            ...
            'KernelFunction', ...
            'squaredexponential', ...
            ...
            'BasisFunction', ...
            'linear', ...
            ...
            'Standardize', ...
            true, ...
            ...
            'Sigma', ...
            initialSigma, ...
            ...
            'SigmaLowerBound', ...
            sigmaLowerBound);


    catch ME2


        %% ====================================================
        %% FALLBACK 2
        %%
        %% Sparse subset-of-regressors GPR.
        %%
        %% Useful for large IMS4 training sets.
        %% ====================================================

        fprintf('\n');

        warning( ...
            ['Stable exact GPR also failed.\n', ...
             'Attempting sparse GPR fallback.\n', ...
             'Exact GPR error:\n%s'], ...
             ME2.message);


        GPRFitStatus = ...
            'SparseGPRFallback';


        activeSetSize = ...
            min( ...
            1000, ...
            numTrainGPR);


        gprMdl = ...
            fitrgp( ...
            X_train_time, ...
            Y_train_HI, ...
            ...
            'KernelFunction', ...
            'squaredexponential', ...
            ...
            'BasisFunction', ...
            'linear', ...
            ...
            'Standardize', ...
            true, ...
            ...
            'FitMethod', ...
            'sr', ...
            ...
            'PredictMethod', ...
            'sr', ...
            ...
            'ActiveSetSize', ...
            activeSetSize, ...
            ...
            'Sigma', ...
            initialSigma, ...
            ...
            'SigmaLowerBound', ...
            sigmaLowerBound);


    end


end


fprintf( ...
    'Final GPR fitting method = %s\n', ...
    GPRFitStatus);


%% ============================================================
%% FUTURE PREDICTION
%% ============================================================

futureTime = ...
    ( ...
    1: ...
    (numSamples + futureHorizon) ...
    )';


[ ...
    HI_pred, ...
    HI_sd, ...
    HI_ci ...
    ] = ...
    predict( ...
    gprMdl, ...
    futureTime);


%% ============================================================
%% CLEAN PREDICTIONS
%% ============================================================

HI_pred(~isfinite(HI_pred)) = ...
    0;


HI_sd(~isfinite(HI_sd)) = ...
    0;


HI_ci(~isfinite(HI_ci)) = ...
    0;


%% ============================================================
%% LIMIT PREDICTED HI RANGE
%% ============================================================

HI_pred( ...
    HI_pred < 0) = ...
    0;


HI_pred( ...
    HI_pred > 1.2) = ...
    1.2;


%% ============================================================
%% CURRENT PROGNOSTIC POINT
%%
%% End of 70% GPR observation/training interval.
%% ============================================================

currentPoint = ...
    numTrainGPR;


%% ============================================================
%% SEARCH FOR FAILURE ONLY AFTER CURRENT POINT
%% ============================================================

futureFailureIdx = ...
    find( ...
    HI_pred( ...
    currentPoint+1:end) ...
    >= ...
    failureThreshold, ...
    1, ...
    'first');


if isempty(futureFailureIdx)


    predictedFailurePoint = ...
        numSamples + ...
        futureHorizon;


else


    predictedFailurePoint = ...
        currentPoint + ...
        futureFailureIdx;


end


%% ============================================================
%% RUL IN SAMPLES
%% ============================================================

RUL_pred_samples = ...
    max( ...
    predictedFailurePoint - ...
    currentPoint, ...
    0);


%% ============================================================
%% RUL IN HOURS
%% ============================================================

RUL_pred_hours = ...
    RUL_pred_samples * ...
    samplingInterval_minutes / ...
    60;


%% ============================================================
%% RUL IN DAYS
%% ============================================================

RUL_pred_days = ...
    RUL_pred_hours / ...
    24;


%% ============================================================
%% STORE RESULTS
%% ============================================================

result.X_bearing = ...
    X;


result.RSE = ...
    RSE;


result.HI = ...
    HI;


result.HI_norm = ...
    HI_norm;


result.HI_min = ...
    HI_min;


result.HI_max = ...
    HI_max;


result.failureThreshold = ...
    failureThreshold;


result.threshold_baseline = ...
    threshold_baseline;


result.threshold_late = ...
    threshold_late;


result.threshold_percentile = ...
    threshold_percentile;


result.gprMdl = ...
    gprMdl;


result.GPRFitStatus = ...
    GPRFitStatus;


result.sigmaLowerBound = ...
    sigmaLowerBound;


result.initialSigma = ...
    initialSigma;


result.timeIndex = ...
    timeIndex;


result.futureTime = ...
    futureTime;


result.HI_pred = ...
    HI_pred;


result.HI_sd = ...
    HI_sd;


result.HI_ci = ...
    HI_ci;


result.currentPoint = ...
    currentPoint;


result.predictedFailurePoint = ...
    predictedFailurePoint;


result.RUL_pred_samples = ...
    RUL_pred_samples;


result.RUL_pred_hours = ...
    RUL_pred_hours;


result.RUL_pred_days = ...
    RUL_pred_days;


result.numSamples = ...
    numSamples;


result.numFeatures = ...
    numFeatures;


result.numTrainGPR = ...
    numTrainGPR;


result.numBaseline = ...
    numBaseline;


result.numLate = ...
    numLate;


result.smoothWindow = ...
    localSmoothWindow;


end

