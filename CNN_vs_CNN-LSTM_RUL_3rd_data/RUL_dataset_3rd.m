%% ============================================================
%% Bearing-Wise RUL Comparison
%%
%% IMS Dataset 4
%%
%% Proposed Method:
%% FFT + Bayesian-Optimized 1-D CNN Features + GPR
%%
%% Benchmark Method:
%% FFT + CNN-LSTM Features + GPR
%% CNN-LSTM WITHOUT Bayesian Optimization
%%
%% Bearing / Channel Mapping:
%%
%% Bearing 1 -> Ch1
%% Bearing 2 -> Ch2
%% Bearing 3 -> Ch3
%% Bearing 4 -> Ch4
%%
%% IMPORTANT:
%% The same downstream:
%%
%% Feature -> RSE -> HI -> GPR -> RUL
%%
%% framework is applied to BOTH methods.
%%
%% Updated GPR:
%% 1. Numerical checks
%% 2. SigmaLowerBound
%% 3. Robust initial Sigma
%% 4. Bayesian-optimized GPR attempted first
%% 5. Stable fallback GPR if Cholesky failure occurs
%% ============================================================


%% ============================================================
%% LOAD PROPOSED FFT-1D-CNN FEATURES
%% ============================================================

load( ...
    'X_FFT_1DCNN_features_IMS_4th_test_BayesOpt_NoNorm.mat');


if ~exist('X_cnn_all_channels','var')

    error( ...
        ['Variable "X_cnn_all_channels" was not found in ', ...
         'X_FFT_1DCNN_features_IMS_4th_test_BayesOpt_NoNorm.mat']);

end


AA_CNN = ...
    X_cnn_all_channels;


clear X_cnn_all_channels;


%% ============================================================
%% LOAD BENCHMARK FFT-CNN-LSTM FEATURES
%% ============================================================

load( ...
    'X_FFT_CNN_LSTM_features_IMS_4th_test_NoBayesOpt.mat');


if ~exist('X_cnn_lstm_all_channels','var')

    error( ...
        ['Variable "X_cnn_lstm_all_channels" was not found in ', ...
         'X_FFT_CNN_LSTM_features_IMS_4th_test_NoBayesOpt.mat']);

end


AA_CNN_LSTM = ...
    X_cnn_lstm_all_channels;


clear X_cnn_lstm_all_channels;


%% ============================================================
%% VERIFY CHANNEL COUNTS
%% ============================================================

numChannelsCNN = ...
    numel(AA_CNN);


numChannelsCNNLSTM = ...
    numel(AA_CNN_LSTM);


fprintf('\n============================================\n');
fprintf('IMS DATASET 4 RUL FEATURE INFORMATION\n');
fprintf('============================================\n');


fprintf( ...
    'Proposed FFT-1D-CNN channels     = %d\n', ...
    numChannelsCNN);


fprintf( ...
    'Benchmark FFT-CNN-LSTM channels = %d\n', ...
    numChannelsCNNLSTM);


if numChannelsCNN ~= numChannelsCNNLSTM

    error( ...
        ['The proposed and benchmark files contain ', ...
         'different numbers of channels.']);

end


if numChannelsCNN ~= 4

    error( ...
        ['This IMS Dataset 4 implementation expects ', ...
         '4 channels. Found %d.'], ...
         numChannelsCNN);

end


%% ============================================================
%% DISPLAY FEATURE DIMENSIONS
%% ============================================================

fprintf('\n============================================\n');
fprintf('CHANNEL-WISE FEATURE DIMENSIONS\n');
fprintf('============================================\n');


for ch = 1:numChannelsCNN

    fprintf( ...
        ['Ch%d Proposed  : %d samples x %d features\n'], ...
        ch, ...
        size(AA_CNN{ch},1), ...
        size(AA_CNN{ch},2));


    fprintf( ...
        ['Ch%d Benchmark : %d samples x %d features\n'], ...
        ch, ...
        size(AA_CNN_LSTM{ch},1), ...
        size(AA_CNN_LSTM{ch},2));

end


